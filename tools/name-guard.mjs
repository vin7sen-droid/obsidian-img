// 自动扩充的人名（tools/names_autofill.py 从当日新闻里查维基生成）。
// 单独放 JSON 是为了让自动流程不改源码、可随时重跑覆盖；合并顺序在内置表之后，冲突时内置表优先。
let EXTRA_NAMES = [];
try {
  const raw = fs.readFileSync(new URL("./names-extra.json", import.meta.url), "utf8");
  EXTRA_NAMES = Object.entries(JSON.parse(raw)).map(([en, zh]) => [en, zh]);
} catch {
  // 文件不存在/格式坏了都不影响主流程，静默跳过
}
const ALL_NAMES = NAMES.concat(EXTRA_NAMES);
const NAME_MAP = new Map(ALL_NAMES.map(([en, zh]) => [en.toLowerCase(), zh]));
const NAME_RE = new RegExp(
  "(?<![\\w])(" + ALL_NAMES.map(([en]) => en.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")).join("|") + ")(?![\\w])",
  "gi"
);
// 兜底：译文里仍是英文人名时直接换中文（引擎偶尔保留原文）
const swapNames = (s) => s.replace(NAME_RE, (m) => NAME_MAP.get(m.toLowerCase()) || m);

// 占位符用全大写字母词（PERSONA/PERSONB…）：实测腾讯在多行同批里会随机吞掉 ZQXnZQX
// 这类带数字的 token，字母词则整批稳定保留。
const PH = /PERSON([A-Z])/gi;
const tok = (i) => `PERSON${String.fromCharCode(65 + i)}`;
const restoreNames = (s, bag) => s.replace(PH, (m, c) => { const k = c.toUpperCase(); return k in bag ? bag[k] : m; });
const lostPlaceholder = (s, bag) =>
  s != null && Object.keys(bag).some((c) => !new RegExp(`PERSON${c}`, "i").test(s));

export { NAMES, ALL_NAMES, NAME_MAP, NAME_RE, swapNames, PH, tok, restoreNames, lostPlaceholder };
